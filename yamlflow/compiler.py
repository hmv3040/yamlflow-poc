"""Emit immutable config snapshots and thin Airflow Python DAGs."""
import hashlib
import json
import shutil
from pathlib import Path

from .config import load_project


def task_id(key):
    # Hash prevents collisions between names containing underscores and separators.
    return key.replace(".", "__") + "_" + hashlib.sha256(key.encode()).hexdigest()[:8]


def compile_project(root, output):
    root, project, nodes = load_project(root)
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    manifest = {"project": project.model_dump(), "nodes": nodes}
    payload = json.dumps(manifest, sort_keys=True, indent=2)
    # Snapshot YAML and fixtures together so tasks cannot see later config edits.
    digest = hashlib.sha256(payload.encode())
    for node in nodes.values():
        if node["kind"] == "source":
            digest.update((root / node["resource"]["fixture"]).read_bytes())
    snapshot = "_snapshot_" + project.name + "_" + digest.hexdigest()[:12]
    bundle = output / snapshot
    bundle.mkdir(exist_ok=True)
    (bundle / "manifest.json").write_text(payload)
    project_copy = bundle / "project"
    project_copy.mkdir(exist_ok=True)
    shutil.copy2(root / "project.yml", project_copy / "project.yml")
    for layer in ("sources", "dw", "metrics"):
        (project_copy / layer).mkdir(exist_ok=True)
        for path in (root / layer).glob("*.y*ml"):
            shutil.copy2(path, project_copy / layer / path.name)
    for node in nodes.values():
        if node["kind"] == "source":
            fixture = node["resource"]["fixture"]
            destination = project_copy / fixture
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(root / fixture, destination)
    files = []
    for pipeline_id, pipeline in sorted(project.pipelines.items()):
        selected = {k: n for k, n in nodes.items() if n["pipeline"] == pipeline_id}
        lines = [
            "# Generated by yamlflow compile. Edit project YAML, not this file.",
            "from datetime import timedelta", "from pathlib import Path", "import pendulum",
            "from airflow.sdk import DAG",
            "from airflow.providers.standard.operators.python import PythonOperator",
            "from yamlflow.engine import run_manifest_task",
            "from yamlflow.snapshot import publish_manifest_snapshot",
            f"MANIFEST = str(Path(__file__).parent / {snapshot!r} / 'manifest.json')",
            f"with DAG(dag_id={pipeline_id!r}, schedule={pipeline.schedule!r},",
            f"         start_date=pendulum.parse({pipeline.start_date!r}, tz={pipeline.timezone!r}),",
            f"         catchup=False, max_active_runs=1, tags=['yamlflow', {project.name!r}],",
            f"         default_args={{'retries': {pipeline.retries}, 'retry_delay': timedelta(seconds={pipeline.retry_delay_seconds})}}) as dag:",
            "    tasks = {}", "    gates = {}",
        ]
        for key, node in selected.items():
            tid = task_id(key)
            lines.extend([
                f"    tasks[{key!r}] = PythonOperator(",
                f"        task_id={tid!r}, python_callable=run_manifest_task, pool='duckdb_access',",
                f"        op_kwargs={{'manifest_path': MANIFEST, 'node_id': {key!r}}})",
            ])
            if node["tests"]:
                lines.extend([
                    f"    gates[{key!r}] = PythonOperator(",
                    f"        task_id={'test__' + tid!r}, python_callable=run_manifest_task, pool='duckdb_access',",
                    f"        op_kwargs={{'manifest_path': MANIFEST, 'node_id': {key!r}, 'action': 'test'}})",
                    f"    tasks[{key!r}] >> gates[{key!r}]",
                ])
            else:
                lines.append(f"    gates[{key!r}] = tasks[{key!r}]")
        for key, node in selected.items():
            for dep in node["depends_on"]:
                lines.append(f"    gates[{dep!r}] >> tasks[{key!r}]")
        lines.extend([
            "    publish = PythonOperator(task_id='publish_analytics_snapshot',",
            "        python_callable=publish_manifest_snapshot, pool='duckdb_access',",
            "        op_kwargs={'manifest_path': MANIFEST})",
            "    list(gates.values()) >> publish",
        ])
        path = output / f"{pipeline_id}.py"
        temporary = path.with_suffix(".tmp")
        temporary.write_text("\n".join(lines) + "\n")
        temporary.replace(path)
        files.append(str(path))
    (output / ".airflowignore").write_text("_snapshot_*\n")
    return files
